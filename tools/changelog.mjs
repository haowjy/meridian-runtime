// A PR body's `## Changelog` section: validate it, merge several into one release entry, render
// that entry into CHANGELOG.md, and read an entry back out for the GitHub Release.
// A section is either one line `None. <reason>` or `### <Section>` blocks of `- ` bullets.

export const SECTIONS = [
  "Upgrade notes",
  "Added",
  "Changed",
  "Deprecated",
  "Removed",
  "Fixed",
  "Security",
];

const CHANGELOG_HEADER = `# Changelog

Entries are rendered from merged PRs' \`## Changelog\` sections by the release job; do not edit this file in a PR.
`;

// A `<...>` with a space in it, or one of the template's own placeholders, left in an entry.
const PLACEHOLDER = /<(?:description|placeholder)>|<[^<>\n]*\s[^<>\n]*>|^(?:-\s+)?(?:TODO|TBD)$/i;

// Lines of `body` with comments blanked and, per line, whether it sits inside a code fence.
function scan(body) {
  const text = body.replace(/<!--[\s\S]*?(?:-->|$)/g, (comment) => comment.replace(/[^\n]/g, ""));
  let fence = null;
  return text.split(/\r?\n/).map((line) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/)?.[1];
    if (fence) {
      if (marker?.[0] === fence[0] && marker.length >= fence.length) fence = null;
      return { line, code: true };
    }
    if (marker) {
      fence = marker;
      return { line, code: true };
    }
    return { line, code: false };
  });
}

const headingOf = ({ line, code }) => (code ? null : line.match(/^(#{1,6})\s+(.*?)\s*$/));

// Returns { errors, notes } where notes is { none: string } or { sections: [{ name, lines }] }.
export function parseNotes(body) {
  const rows = scan(body);
  const errors = [];
  const starts = rows.flatMap((row, i) => {
    const heading = headingOf(row);
    return heading?.[1] === "##" && heading[2] === "Changelog" ? [i] : [];
  });
  if (starts.length === 0) {
    return { errors: ["no '## Changelog' heading (it must read exactly that)"], notes: null };
  }
  if (starts.length > 1) errors.push("more than one '## Changelog' section; keep exactly one");

  let end = rows.length;
  for (let i = starts[0] + 1; i < rows.length; i++) {
    if (headingOf(rows[i])?.[1].length <= 2) {
      end = i;
      break;
    }
  }
  const block = rows.slice(starts[0] + 1, end);
  const content = block.map((row) => row.line);
  const first = content.findIndex((line) => line.trim());
  if (first < 0) {
    errors.push("'## Changelog' is empty: write 'None. <reason>' or '### <Section>' blocks");
    return { errors, notes: null };
  }

  for (const line of content) {
    const placeholder = line
      .replace(/`[^`]*`/g, "")
      .trim()
      .match(PLACEHOLDER);
    if (placeholder) errors.push(`leftover placeholder in: ${line.trim()}`);
  }

  if (content[first].trim().startsWith("None.")) {
    const none = content[first].trim();
    if (!/^None\.\s+\S/.test(none))
      errors.push("'None.' needs a reason: 'None. Internal refactor.'");
    if (content.slice(first + 1).some((line) => line.trim())) {
      errors.push("'None. <reason>' must be the only content under '## Changelog'");
    }
    return { errors, notes: { none } };
  }

  const sections = [];
  for (const { line, code } of block) {
    const text = line.trim();
    const heading = code ? null : text.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      const name = heading[2].trim();
      if (heading[1] !== "###" || !SECTIONS.includes(name)) {
        errors.push(
          `'${text}' is not a changelog section; use '### <Section>' with one of: ${SECTIONS.join(", ")}`,
        );
      } else if (sections.some((s) => s.name === name)) {
        errors.push(`duplicate '### ${name}' section`);
      }
      sections.push({ name, lines: [] });
    } else if (text) {
      const current = sections.at(-1);
      if (!current) errors.push(`expected 'None. <reason>' or '### <Section>', got: ${text}`);
      else {
        if (current.lines.every((l) => !l.trim()) && !text.startsWith("- ")) {
          errors.push(`'### ${current.name}' must start with a '- ' bullet`);
        }
        current.lines.push(line.trimEnd());
      }
    } else sections.at(-1)?.lines.push("");
  }
  for (const section of sections) {
    while (section.lines.at(-1) === "") section.lines.pop();
    if (section.lines.length === 0) errors.push(`'### ${section.name}' has no '- ' bullet`);
  }
  return { errors, notes: { sections } };
}

// Merges notes in order; sections come out in the canonical order. `None.` lines count only when
// no entry has sections.
export function mergeNotes(list) {
  const merged = new Map();
  let none = null;
  for (const notes of list) {
    if (notes.none) none = notes.none;
    for (const { name, lines } of notes.sections ?? []) {
      merged.set(name, [...(merged.get(name) ?? []), ...lines]);
    }
  }
  if (merged.size === 0) return { none: none ?? "None. No changelog entries." };
  return {
    sections: SECTIONS.filter((n) => merged.has(n)).map((name) => ({
      name,
      lines: merged.get(name),
    })),
  };
}

export function renderEntry(version, date, notes) {
  const body =
    notes.none ?? notes.sections.map((s) => [`### ${s.name}`, ...s.lines].join("\n")).join("\n\n");
  return `## [${version}] - ${date}\n\n${body}\n`;
}

// Puts `entry` above the newest release in `changelog` (a missing file starts from the header).
export function addEntry(changelog, entry) {
  const text = changelog ?? CHANGELOG_HEADER;
  const at = text.search(/^## \[/m);
  return at < 0
    ? `${text.trimEnd()}\n\n${entry}`
    : `${text.slice(0, at)}${entry}\n${text.slice(at)}`;
}

// The body of `## [version]`, or "" when the file or the entry is missing.
export function entryBody(changelog, version) {
  const lines = (changelog ?? "").split("\n");
  const start = lines.findIndex((line) => line.startsWith(`## [${version}]`));
  if (start < 0) return "";
  const rest = lines.slice(start + 1);
  const stop = rest.findIndex((line) => line.startsWith("## "));
  return (stop < 0 ? rest : rest.slice(0, stop)).join("\n").trim();
}
